#!/usr/bin/env bash
#
# download.sh - Cross-platform artifact downloader for AgenticLens setup skill
#
# Detects host platform and architecture, downloads the precompiled binary from
# GitHub Releases, installs it into the destination directory, sets executable
# permissions, and writes a protective .gitignore.
#
# Zero compilation required. Zero Go/Node toolchain dependency.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SKILL_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"

REPO="${AGENTIC_LENS_REPO:-NiltonDuarte/AgenticLens}"
DEST_DIR="${AGENTIC_LENS_BIN_DIR:-${SKILL_ROOT}/bin}"
VERSION="${AGENTIC_LENS_VERSION:-latest}"
LOCAL_BIN="${AGENTIC_LENS_LOCAL_BINARY:-}"
FORCE=0
DRY_RUN=0

usage() {
    cat <<EOF
Usage: download.sh [OPTIONS]

Options:
  --version <version>    Release version to download (default: latest)
  --dest <dir>           Destination binary directory (default: .opencode/skills/agentic-lens-setup/bin)
  --local-bin <path>     Use local prebuilt binary instead of downloading (testing escape hatch)
  --force                Overwrite existing binary if present
  --dry-run              Print resolved platform, architecture, and download URL without downloading
  --help                 Show this help message
EOF
    exit 0
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --version)
            VERSION="$2"
            shift 2
            ;;
        --dest)
            DEST_DIR="$2"
            shift 2
            ;;
        --local-bin)
            LOCAL_BIN="$2"
            shift 2
            ;;
        --force)
            FORCE=1
            shift
            ;;
        --dry-run)
            DRY_RUN=1
            shift
            ;;
        --help|-h)
            usage
            ;;
        *)
            echo "Error: Unknown argument $1" >&2
            exit 1
            ;;
    esac
done

# Detect Operating System
OS_RAW="$(uname -s)"
case "$OS_RAW" in
    Darwin)
        OS="darwin"
        ;;
    Linux)
        OS="linux"
        ;;
    MINGW*|MSYS*|CYGWIN*|Windows_NT)
        OS="windows"
        ;;
    *)
        echo "Error: Unsupported operating system: $OS_RAW" >&2
        exit 1
        ;;
esac

# Detect Architecture
ARCH_RAW="$(uname -m)"
case "$ARCH_RAW" in
    x86_64|amd64)
        ARCH="amd64"
        ;;
    arm64|aarch64)
        ARCH="arm64"
        ;;
    *)
        echo "Error: Unsupported architecture: $ARCH_RAW" >&2
        exit 1
        ;;
esac

BIN_NAME="agentic-lens"
BIN_EXT=""
if [[ "$OS" == "windows" ]]; then
    BIN_NAME="agentic-lens.exe"
    BIN_EXT=".exe"
fi

REMOTE_BIN="agentic-lens-${OS}-${ARCH}${BIN_EXT}"

if [[ "$VERSION" == "latest" ]]; then
    DOWNLOAD_URL="https://github.com/${REPO}/releases/latest/download/${REMOTE_BIN}"
else
    DOWNLOAD_URL="https://github.com/${REPO}/releases/download/${VERSION}/${REMOTE_BIN}"
fi

TARGET_BIN="${DEST_DIR}/${BIN_NAME}"

if [[ $DRY_RUN -eq 1 ]]; then
    echo "Platform: ${OS}"
    echo "Architecture: ${ARCH}"
    echo "Version: ${VERSION}"
    echo "Destination: ${TARGET_BIN}"
    echo "Remote Binary: ${REMOTE_BIN}"
    echo "Download URL: ${DOWNLOAD_URL}"
    exit 0
fi

if [[ -f "$TARGET_BIN" && $FORCE -eq 0 ]]; then
    echo "AgenticLens binary already exists at ${TARGET_BIN} (use --force to overwrite)."
    exit 0
fi

# Ensure destination directory exists
mkdir -p "$DEST_DIR"

# Write protective .gitignore if not present
GITIGNORE="${DEST_DIR}/.gitignore"
if [[ ! -f "$GITIGNORE" ]]; then
    cat <<'GITIGNORE_EOF' > "$GITIGNORE"
# Automatically generated by AgenticLens downloader
# Prevent accidental git tracking of precompiled binaries
*
!.gitignore
GITIGNORE_EOF
fi

# If a local binary override is specified and valid, install it directly
if [[ -n "$LOCAL_BIN" ]]; then
    if [[ ! -f "$LOCAL_BIN" ]]; then
        echo "Error: Specified local binary does not exist: $LOCAL_BIN" >&2
        exit 1
    fi
    echo "Installing local precompiled binary from ${LOCAL_BIN} to ${TARGET_BIN}..."
    cp "$LOCAL_BIN" "$TARGET_BIN"
    chmod +x "$TARGET_BIN"
    echo "Successfully installed AgenticLens binary at ${TARGET_BIN}"
    exit 0
fi

echo "Downloading AgenticLens binary (${OS}/${ARCH}, ${VERSION})..."

TEMP_BIN="${TARGET_BIN}.tmp.$$"
cleanup() {
    rm -f "$TEMP_BIN"
}
trap cleanup EXIT

DOWNLOAD_SUCCESS=0

# Attempt 1: curl
if command -v curl >/dev/null 2>&1; then
    echo "Attempting download via curl..."
    if curl -fsSL -o "$TEMP_BIN" "$DOWNLOAD_URL"; then
        DOWNLOAD_SUCCESS=1
    fi
fi

# Attempt 2: wget
if [[ $DOWNLOAD_SUCCESS -eq 0 ]] && command -v wget >/dev/null 2>&1; then
    echo "Attempting download via wget..."
    if wget -q -O "$TEMP_BIN" "$DOWNLOAD_URL"; then
        DOWNLOAD_SUCCESS=1
    fi
fi

if [[ $DOWNLOAD_SUCCESS -eq 0 || ! -f "$TEMP_BIN" ]]; then
    echo "Error: Failed to download ${REMOTE_BIN} from ${DOWNLOAD_URL}" >&2
    echo "Please check network connectivity or verify release exists at https://github.com/${REPO}/releases" >&2
    exit 1
fi

mv "$TEMP_BIN" "$TARGET_BIN"
chmod +x "$TARGET_BIN"

echo "Successfully installed AgenticLens binary at ${TARGET_BIN}"
