#!/usr/bin/env bash
#
# download-agentic-lens.sh - Cross-platform artifact downloader for AgenticLens
#
# Detects host platform and architecture, downloads the precompiled binary from
# GitHub Releases, unpacks it into the destination directory, sets executable
# permissions, and writes a protective .gitignore.
#
# Zero compilation required. Zero Go/Node toolchain dependency.

set -euo pipefail

REPO="NiltonDuarte/AgenticLens"
DEST_DIR="${AGENTIC_LENS_BIN_DIR:-.opencode/skills/agentic-lens-setup/bin}"
VERSION="${AGENTIC_LENS_VERSION:-latest}"
LOCAL_BIN="${AGENTIC_LENS_LOCAL_BINARY:-}"
FORCE=0
DRY_RUN=0

usage() {
    cat <<EOF
Usage: download-agentic-lens.sh [OPTIONS]

Options:
  --version <version>    Release version to download (default: latest)
  --dest <dir>           Destination binary directory (default: .opencode/skills/agentic-lens-setup/bin)
  --local-bin <path>     Use local prebuilt binary instead of downloading (testing escape hatch)
  --force                Overwrite existing binary if present
  --dry-run              Print resolved platform, architecture, and download URL without downloading
  --help                 Show this help message
EOF
    exit 0
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --version)
            VERSION="$2"
            shift 2
            ;;
        --dest)
            DEST_DIR="$2"
            shift 2
            ;;
        --local-bin)
            LOCAL_BIN="$2"
            shift 2
            ;;
        --force)
            FORCE=1
            shift
            ;;
        --dry-run)
            DRY_RUN=1
            shift
            ;;
        --help|-h)
            usage
            ;;
        *)
            echo "Error: Unknown argument $1" >&2
            exit 1
            ;;
    esac
done

# Detect Operating System
OS_RAW="$(uname -s)"
case "$OS_RAW" in
    Darwin)
        OS="darwin"
        ;;
    Linux)
        OS="linux"
        ;;
    MINGW*|MSYS*|CYGWIN*|Windows_NT)
        OS="windows"
        ;;
    *)
        echo "Error: Unsupported operating system: $OS_RAW" >&2
        exit 1
        ;;
esac

# Detect Architecture
ARCH_RAW="$(uname -m)"
case "$ARCH_RAW" in
    x86_64|amd64)
        ARCH="amd64"
        ;;
    arm64|aarch64)
        ARCH="arm64"
        ;;
    *)
        echo "Error: Unsupported architecture: $ARCH_RAW" >&2
        exit 1
        ;;
esac

BIN_NAME="agentic-lens"
if [[ "$OS" == "windows" ]]; then
    BIN_NAME="agentic-lens.exe"
    ARCHIVE_EXT="zip"
else
    ARCHIVE_EXT="tar.gz"
fi

if [[ "$VERSION" == "latest" ]]; then
    ARCHIVE_NAME="agentic-lens-${OS}-${ARCH}.${ARCHIVE_EXT}"
    DOWNLOAD_URL="https://github.com/${REPO}/releases/latest/download/${ARCHIVE_NAME}"
else
    ARCHIVE_NAME="agentic-lens-${VERSION}-${OS}-${ARCH}.${ARCHIVE_EXT}"
    DOWNLOAD_URL="https://github.com/${REPO}/releases/download/${VERSION}/${ARCHIVE_NAME}"
fi

TARGET_BIN="${DEST_DIR}/${BIN_NAME}"

if [[ $DRY_RUN -eq 1 ]]; then
    echo "Platform: ${OS}"
    echo "Architecture: ${ARCH}"
    echo "Version: ${VERSION}"
    echo "Destination: ${TARGET_BIN}"
    echo "Archive Name: ${ARCHIVE_NAME}"
    echo "Download URL: ${DOWNLOAD_URL}"
    exit 0
fi

if [[ -f "$TARGET_BIN" && $FORCE -eq 0 ]]; then
    echo "AgenticLens binary already exists at ${TARGET_BIN} (use --force to overwrite)."
    exit 0
fi

# Ensure destination directory exists
mkdir -p "$DEST_DIR"

# Write protective .gitignore if not present
GITIGNORE="${DEST_DIR}/.gitignore"
if [[ ! -f "$GITIGNORE" ]]; then
    cat <<'GITIGNORE_EOF' > "$GITIGNORE"
# Automatically generated by AgenticLens downloader
# Prevent accidental git tracking of precompiled binaries
*
!.gitignore
GITIGNORE_EOF
fi

# If a local binary override is specified and valid, install it directly
if [[ -n "$LOCAL_BIN" ]]; then
    if [[ ! -f "$LOCAL_BIN" ]]; then
        echo "Error: Specified local binary does not exist: $LOCAL_BIN" >&2
        exit 1
    fi
    echo "Installing local precompiled binary from ${LOCAL_BIN} to ${TARGET_BIN}..."
    cp "$LOCAL_BIN" "$TARGET_BIN"
    chmod +x "$TARGET_BIN"
    echo "Successfully installed AgenticLens binary at ${TARGET_BIN}"
    exit 0
fi

# Create secure temporary directory for download and unpacking
TMP_DIR="$(mktemp -d)"
cleanup() {
    rm -rf "$TMP_DIR"
}
trap cleanup EXIT

echo "Downloading AgenticLens (${OS}/${ARCH}, ${VERSION})..."

DOWNLOAD_SUCCESS=0

# Attempt 1: GitHub CLI (gh) if authenticated and available
if command -v gh >/dev/null 2>&1; then
    echo "Attempting download via GitHub CLI..."
    GH_ARGS=(release download)
    if [[ "$VERSION" != "latest" ]]; then
        GH_ARGS+=("$VERSION")
    fi
    GH_ARGS+=(--repo "$REPO" --pattern "$ARCHIVE_NAME" --dir "$TMP_DIR")
    if gh "${GH_ARGS[@]}" >/dev/null 2>&1; then
        DOWNLOAD_SUCCESS=1
    fi
fi

# Attempt 2: curl
if [[ $DOWNLOAD_SUCCESS -eq 0 ]] && command -v curl >/dev/null 2>&1; then
    echo "Attempting download via curl..."
    if curl -fsSL -o "${TMP_DIR}/${ARCHIVE_NAME}" "$DOWNLOAD_URL"; then
        DOWNLOAD_SUCCESS=1
    fi
fi

# Attempt 3: wget
if [[ $DOWNLOAD_SUCCESS -eq 0 ]] && command -v wget >/dev/null 2>&1; then
    echo "Attempting download via wget..."
    if wget -q -O "${TMP_DIR}/${ARCHIVE_NAME}" "$DOWNLOAD_URL"; then
        DOWNLOAD_SUCCESS=1
    fi
fi

if [[ $DOWNLOAD_SUCCESS -eq 0 ]]; then
    echo "Error: Failed to download ${ARCHIVE_NAME} from ${DOWNLOAD_URL}" >&2
    echo "Please check network connectivity or verify release exists at https://github.com/${REPO}/releases" >&2
    exit 1
fi

echo "Extracting ${ARCHIVE_NAME}..."
if [[ "$ARCHIVE_EXT" == "tar.gz" ]]; then
    tar -xzf "${TMP_DIR}/${ARCHIVE_NAME}" -C "$TMP_DIR"
elif [[ "$ARCHIVE_EXT" == "zip" ]]; then
    unzip -q -o "${TMP_DIR}/${ARCHIVE_NAME}" -d "$TMP_DIR"
fi

# Locate the executable in unpacked files
FOUND_BIN=""
if [[ -f "${TMP_DIR}/${BIN_NAME}" ]]; then
    FOUND_BIN="${TMP_DIR}/${BIN_NAME}"
elif [[ -f "${TMP_DIR}/bin/${BIN_NAME}" ]]; then
    FOUND_BIN="${TMP_DIR}/bin/${BIN_NAME}"
else
    # Search recursively for matching binary name
    FOUND_BIN="$(find "$TMP_DIR" -maxdepth 2 -type f -name "$BIN_NAME" | head -n 1)"
fi

if [[ -z "$FOUND_BIN" || ! -f "$FOUND_BIN" ]]; then
    echo "Error: Could not locate ${BIN_NAME} inside downloaded archive." >&2
    exit 1
fi

mv "$FOUND_BIN" "$TARGET_BIN"
chmod +x "$TARGET_BIN"

echo "Successfully installed AgenticLens binary at ${TARGET_BIN}"
